def pixels(ch: str):
    """美咲の字形と同じ形（8 行 x 7 列の 0/255）と、送りを返す。無ければ None。"""
    rows = OVERRIDES.get(ch)
    if rows is None:
        return None
    width = len(rows[0])
    out = [[0] * 7 for _ in range(8)]
    for y, row in enumerate(rows):
        assert len(row) == width, (ch, y)
        for x, v in enumerate(row):
            if v == '#':
                out[y][x] = 255
    return out, width + 1
